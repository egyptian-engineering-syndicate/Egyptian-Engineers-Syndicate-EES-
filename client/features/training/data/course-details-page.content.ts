const outcomesTitle = "مخرجات الدورة"
const topicsTitle = "محاور الدورة"
const detailsBreadcrumbLabel = "تفاصيل الدورة"

/**
 * Temporary adapter: composes the listing entry with the per-course copy above,
 * falling back to the first course for an unknown id until the Directus queries
 * land. Keep the `courseId` argument so callers already pass it.
 */
export function getCourseDetailsPageContent(
  courseId: string
): CourseDetailsPageContent {
  const [firstCourse] = trainingPageContent.courses
  const course =
    trainingPageContent.courses.find((entry) => entry.id === courseId) ??
    firstCourse
  const detail = courseDetails[course.id] ?? courseDetails[firstCourse.id]

  return {
    breadcrumbs: [
      { label: "الرئيسية", href: "/" },
      { label: trainingPageContent.title, href: "/training" },
      { label: detailsBreadcrumbLabel },
    ],
    overview: {
      title: course.title,
      paragraphs: detail.paragraphs,
      outcomesTitle,
      outcomes: detail.outcomes,
      image: course.image,
    },
    topics: {
      title: topicsTitle,
      topics: detail.topics,
    },
    subscription: {
      ...subscription,
      price: course.price,
    },
  }
}
