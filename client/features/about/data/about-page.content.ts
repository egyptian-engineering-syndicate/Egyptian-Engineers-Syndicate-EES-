function memberImage(file: string, alt: string) {
  return { src: `/images/about/board/${file}`, alt }
}

function boardMember(
  id: string,
  name: string,
  role: string,
  file: string,
  alt: string
) {
  return {
    id,
    name,
    role,
    detailsHref: `/about/${id}`,
    image: memberImage(file, alt),
  }
}

